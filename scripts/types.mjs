// Generates frontend/src/shared/api-types.ts from the backend's OpenAPI schema (W3.9).
// Run `npm run types` after changing anything in backend/app/schemas.py or a router.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TYPES_FILE = join(root, "frontend", "src", "shared", "api-types.ts");

const HEADER = "// Generated by `npm run types` from the backend's OpenAPI schema. Don't edit by hand.\n\n";

export async function generateTypes() {
  const schema = execFileSync("uv", ["run", "--quiet", "python", "-m", "app.main"], {
    cwd: root,
    encoding: "utf8",
  });
  const ast = await openapiTS(JSON.parse(schema));
  return HEADER + astToString(ast);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TYPES_FILE, await generateTypes());
  console.log("Updated frontend/src/shared/api-types.ts");
}
